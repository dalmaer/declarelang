import { chromium, devices } from '/Users/temkin/Code/eval-venue-checkout-react-1/work/app/node_modules/playwright/index.mjs'
const phone = process.argv[2] === 'phone'
const browser = await chromium.launch({ channel: 'chrome' })
const ctx = await browser.newContext(phone ? { ...devices['iPhone 13'], deviceScaleFactor: 2 } : { viewport: { width: 1280, height: 860 } })
const page = await ctx.newPage()
page.on('pageerror', (e) => console.log(`pageerror: ${e.message}`))
page.on('request', (r) => r.method() === 'POST' && console.log('POST', r.url(), r.postData()))
await page.goto('http://127.0.0.1:5173/performances/p02')
await page.waitForTimeout(800)
const free = page.locator('[data-state=free][data-section=DC]')
await free.nth(3).click(); await free.nth(4).click()
await page.getByRole('link', { name: 'Continue' }).click()
await page.waitForTimeout(500)
await page.screenshot({ path: `${phone?'p':'d'}-checkout-empty.png`, fullPage: true })
await page.getByLabel('Email').fill('ada@example.com')
await page.getByLabel('Name on card').fill('Ada Lovelace')
await page.getByLabel('Card number').pressSequentially('4242424242424242')
console.log('number shown:', await page.getByLabel('Card number').inputValue())
await page.getByLabel('Expiry').pressSequentially('428')
await page.getByLabel('Security code').fill('123')
await page.getByLabel('Street address').fill('1 Main St')
await page.getByLabel('City').fill('Springfield')
await page.getByLabel('Country').selectOption('US')
await page.getByLabel('Postal code').fill('1234')
await page.getByLabel('Street address').focus()
await page.waitForTimeout(300)
await page.screenshot({ path: `${phone?'p':'d'}-checkout-filled.png`, fullPage: true })
await page.getByLabel('Postal code').fill('94103')
const pay = page.getByRole('button', { name: /^Pay \$/ })
console.log('pay label:', await pay.textContent())
await pay.dblclick()
await page.waitForTimeout(200)
await page.screenshot({ path: `${phone?'p':'d'}-checkout-paying.png` })
await page.waitForURL('**/tickets', { timeout: 8000 })
await page.waitForTimeout(500)
await page.screenshot({ path: `${phone?'p':'d'}-tickets.png`, fullPage: true })
await page.getByRole('article').first().waitFor(); console.log('articles', await page.getByRole('article').count(), await page.getByText(/^Sent to/).textContent())
await browser.close()
