import { helpers } from "./lib.mjs";
export default async (ctx) => {
  const { page, sleep, shot, role, text } = ctx;
  const h = helpers(ctx);
  await h.pickPerf("Friday 13 November");
  await shot("p-hall.png");
  const a = await h.pickSeats(2, "Orchestra");
  const b = await h.pickSeats(1, "Grand Tier");
  console.log("seats:", a, b, "summary:", await h.summary());
  await shot("p-chosen.png");
  await role("button", "Continue to payment").click(); await sleep(600);
  await shot("p-checkout.png");
  await h.fill("Email", "someone@else.com");
  // sign in halfway
  const signIns = await page.$$('::-p-aria([name="Sign in"][role="button"])');
  console.log("sign in buttons:", signIns.length);
  await signIns[signIns.length - 1].click(); await sleep(600);
  await shot("p-signin.png");
  await h.fill("Email", "ada@example.com");
  await h.fill("Password", "wrong one");
  await page.keyboard.press("Enter"); await sleep(800);
  console.log("wrong pw msg:", (await text()).match(/.*match.*/)?.[0]);
  await h.fill("Password", "correct horse battery");
  await page.keyboard.press("Enter"); await sleep(1500);
  await shot("p-signedin.png");
  const t = await text();
  console.log("cards:", t.match(/Visa ending 4242|Mastercard ending 4444|Expire[sd] \d\d\/\d\d/g));
  await h.fill("Security code", "000");
  const pay = (await page.evaluate(() => [...document.querySelectorAll("[role=button],button")].map((e) => e.getAttribute("aria-label") || e.textContent).filter((n) => n.startsWith("Pay"))));
  console.log("pay:", pay);
  await (await page.$(`::-p-aria(${pay[0]})`)).click(); await sleep(2600);
  console.log("declined:", (await text()).match(/.*declined.*/i)?.[0]);
  await shot("p-declined.png");
  await page.locator('::-p-aria([name="A new card"][role="radio"])').click(); await sleep(300);
  console.log("email kept:", await h.value("Email"), "name:", await h.value("Name on card"), "postal:", await h.value("Postal code"));
  await h.fill("Card number", "4242424242424242");
  await h.fill("Expiry (MM / YY)", "1129");
  await h.fill("Security code", "321");
  await h.fill("Postal code", "WC1N");
  await page.keyboard.press("Tab"); await sleep(300);
  console.log("postal msg:", (await text()).match(/.*UK postcode.*/)?.[0]);
  await shot("p-postal.png");
  await h.fill("Postal code", "WC1N 1AB");
  await (await page.$(`::-p-aria(${pay[0]})`)).click(); await sleep(2800);
  await shot("p-tickets.png");
  console.log((await text()).match(/Sent to .*/)?.[0]);
};
