// tools/internal/viewer-reference.mjs — the platform classes the Viewer links
// to their reference pages, written as an include the Viewer compiles in
// (library/platform-apps/viewer/reference.declare), so every host has the list
// without fetching anything. The names are the runtime's registry and the
// library's auto-included classes: every class a program can name as a tag.
// A derive rule (tools/internal/derive.mjs "viewer-reference") keeps it current.

import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "../..");
const OUT = join(ROOT, "library/platform-apps/viewer/reference.declare");

const { REGISTRY_MANIFEST } = await import(join(ROOT, "runtime/dist/registry.js"));
const library = JSON.parse(readFileSync(join(ROOT, "library/autoincludes.json"), "utf8"));
const names = [...new Set([...REGISTRY_MANIFEST.map((e) => e.name), ...Object.keys(library).filter((k) => !k.startsWith("$"))])].sort();

const lines = [];
for (let i = 0; i < names.length; i += 8) lines.push("        " + names.slice(i, i + 8).map((n) => JSON.stringify(n)).join(", "));
const text = `// GENERATED by tools/internal/viewer-reference.mjs (npm run derive) — do not edit.
//
// The platform's classes, each with a reference page: the runtime's registry
// and the library's auto-included classes. The Viewer links a tag naming one
// to its page.

script {
    const REFERENCE_CLASSES: string[] = [
${lines.join(",\n")}
        ]
    }
`;
if (!existsSync(OUT) || readFileSync(OUT, "utf8") !== text) {
  writeFileSync(OUT, text);
  console.log(`viewer-reference: wrote ${names.length} names`);
}
